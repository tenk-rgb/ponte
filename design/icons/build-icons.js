function inner(name) {
  const i = ICONS[name];
  let out = '';
  if (i.body) out += `<path d="${i.body}" fill="currentColor" fill-opacity=".22" stroke="none" />`;
  if (i.line) out += `<path d="${i.line}" />`;
  for (const d of i.dots || []) out += `<path d="${d}" fill="currentColor" stroke="none" />`;
  return out;
}
